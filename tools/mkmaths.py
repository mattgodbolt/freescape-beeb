#!/usr/bin/env python3
"""The maths tables and constants for the assembler, from the model.

    .venv/bin/python -I tools/mkmaths.py build/maths

writes into that directory:

    consts.6502   the constants, and the tables as baron lists: include
                  it before src/maths.6502 and src/project.6502
    tables.6502   the tables themselves, labelled and page-aligned:
                  include it where they're to live (HAZEL, in the engine)

tools/model/maths.py builds every table, so the 6502 reads the model's own
bytes. A change of field of view is a change of FX and FY there: only
PROJ_RECIP depends on them.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from model import maths  # noqa: E402

HEADER = "\\ Generated by tools/mkmaths.py from tools/model/maths.py: don't edit."


def blist(name, values):
    lines = [f"{name} = {{"]
    for i in range(0, len(values), 16):
        chunk = ", ".join(str(v) for v in values[i:i + 16])
        lines.append(f"    {chunk}{',' if i + 16 < len(values) else ''}")
    lines.append("}")
    return "\n".join(lines)


def consts():
    m = maths
    values = {
        "PROJ_XC": m.XC,
        "PROJ_YC": m.YC,
        "PROJ_ZNEAR": m.ZNEAR,
        "PROJ_ZBITS": m.PROJ_ZBITS,
        "PROJ_IBITS": m.PROJ_IBITS,
        "PROJ_SMIN": m.PROJ_SMIN,
        "PROJ_SMAX": m.PROJ_SMAX,
        "PROJ_SLOW": m.PROJ_SLOW,
    }
    return "\n".join([
        HEADER,
        "",
        *(f"{k} = {v}" for k, v in values.items()),
        "",
        "\\ quarter squares: f(j) and f(j - 255), f(n) = n * n DIV 4, j = 0..511",
        blist("MATHS_SQ", m.SQ),
        blist("MATHS_NG", m.NG),
        "",
        "\\ the projection's reciprocals, for Zi = 512..1023",
        blist("PROJ_RECIP", m.RECIP),
        "",
        "\\ twice the bit length of each byte, for the projection's dispatch",
        blist("PROJ_BL2", [2 * b.bit_length() for b in range(256)]),
        "",
    ])


TABLES = HEADER + r"""

\ Each table is page-aligned, so a multiplier patched into an operand's low
\ byte is the whole offset (src/maths.6502, src/project.6502).
ALIGN 256
.sq_lo      EQUB LO(MATHS_SQ)
.sq_hi      EQUB HI(MATHS_SQ)
.ng_lo      EQUB LO(MATHS_NG)
.ng_hi      EQUB HI(MATHS_NG)
.proj_rlo   EQUB LO(PROJ_RECIP)
.proj_rhi   EQUB HI(PROJ_RECIP)
.proj_bl2   EQUB PROJ_BL2
.maths_tables_end
"""


def cases(seed=1987):
    """The check's cases, with the model's answers (tools/mathscheck.mjs).

    mul is checked exhaustively by the harness itself, against v * m; the
    model's mul is that exactly (checked here on every byte product and on
    the edges). dot3 and project get the edges and many random cases."""
    import random
    m = maths
    rnd = random.Random(seed)

    # the byte products the tables give, all of them; and mul's edges
    for a in range(256):
        for b in range(256):
            assert m.umul8(a, b) == a * b
    for v in (-32768, -32767, -256, -255, -1, 0, 1, 255, 256, 32767):
        for c in (-128, -127, -64, -1, 0, 1, 64, 127):
            assert m.mul(v, c) == v * c

    s16 = (-32768, -32767, -257, -256, -255, -1, 0, 1, 255, 256, 32767)
    s8 = (-128, -127, -64, -1, 0, 1, 63, 64, 127)
    dot = []
    for v in s16:
        for c in s8:
            for w in (0, -32768, 32767):
                dot.append(((c, -c if c > -128 else 127, c), (v, w, v)))
    for _ in range(40000):
        row = tuple(rnd.randint(-128, 127) for _ in range(3))
        v = tuple(rnd.randint(-32768, 32767) for _ in range(3))
        dot.append((row, v))
    for _ in range(20000):
        # the engine's own: unit rows (1.0 = 64), coordinates in an area
        row = tuple(rnd.randint(-64, 64) for _ in range(3))
        v = tuple(rnd.randint(-8192, 8192) for _ in range(3))
        dot.append((row, v))
    dot = [[*row, *v, m.dot3(row, v)] for row, v in dot]

    lim = 1 << 23
    zs = [m.ZNEAR, m.ZNEAR + 1, lim - 1]
    for k in range(m.ZNEAR.bit_length(), 23):
        zs += [(1 << k) - 1, 1 << k, (1 << k) + 1]
    xs = [0, 1, -1, 2, -2, 255, -256, 65535, -65536, lim - 1, -lim]
    proj = []
    for z in zs:
        for x in xs:
            for y in (0, x, -x if -x < lim else 0, z, -z):
                proj.append((x, y, z))
        for r in (0.5, 0.656, 1, 3.9, 4.1, 8, 16, 25, 40, 300):
            a = min(lim - 1, int(r * z))
            proj += [(a, a // 2, z), (-a, -a // 2, z), (a, -a, z)]
    for band in (0.7, 4, 40, None):
        for _ in range(25000):
            if band is None:
                z = rnd.randint(m.ZNEAR, lim - 1)
                x, y = rnd.randint(-lim, lim - 1), rnd.randint(-lim, lim - 1)
            else:
                # Z log-uniform over Driller's depths (docs/research/maths.md)
                z = int(m.ZNEAR * (742000 / m.ZNEAR) ** rnd.random())
                a = min(lim - 1, int(band * z))
                x = rnd.randint(-a, a)
                y = rnd.randint(-a // 2, a // 2)
            proj.append((x, y, z))
    proj = [[x, y, z, *m.project(x, y, z)] for x, y, z in proj]
    return {"dot": dot, "proj": proj}


def survey(n=100000, seed=7):
    """The projection methods' errors against exact division, in
    sixteenths, over Driller's depths (docs/research/maths.md): each
    method's worst on screen (|X| <= 0.66 Z, the view's half-width), its
    worst for |X| <= 4 Z, and whether it ever goes backwards as X or Z
    grows."""
    import math
    import random
    m = maths
    rnd = random.Random(seed)

    def ilog2(v, mbits):
        # v's log2 from its top mbits bits, truncated (a table's index)
        e = v.bit_length() - mbits
        return e + math.log2(m._shr(v, e))

    def logmethod(mbits, abits):
        # P = 2^(log2 FX + log2 |X| - log2 Z), logs from mbits-bit
        # mantissas, the difference truncated to abits bits of fraction
        # for the antilog's table (Elite's LL28: 8 and 5)
        def p(x, z):
            if x == 0:
                return 0
            d = math.log2(m.FX) + ilog2(abs(x), mbits) - ilog2(z, mbits)
            q = math.floor(d * (1 << abits)) / (1 << abits)
            return int(2 ** q) * (1 if x > 0 else -1)
        return p

    def recip(rbits):
        # the chosen shifts with R kept to rbits significant bits, exactly
        def p(x, z):
            s = z.bit_length() - m.PROJ_ZBITS
            r = m.RECIP[m._shr(z, s + 3) - 512]
            drop = r.bit_length() - rbits
            r = (r >> drop) << drop
            xp = m._shr(abs(x), s)
            v = (xp * r) >> 16
            return v if x >= 0 else -v
        return p

    def chosen(x, z):
        return m.project(x, 0, z)[0] - m.XC

    def exact3(x, z):
        s = z.bit_length() - m.PROJ_ZBITS
        r = m.RECIP[m._shr(z, s + 3) - 512]
        xp = m._shr(abs(x), s)
        x1, x0, r1, r0 = xp >> 8, xp & 255, r >> 8, r & 255
        v = x1 * r1 + ((x1 * r0 + x0 * r1) >> 8) + 1
        return v if x >= 0 else -v

    methods = [
        ("chosen: R 16-bit, three high-byte products", chosen),
        ("R 16-bit, middle products summed exactly", exact3),
        ("R kept to 9 bits (two products)", recip(9)),
        ("log/antilog, 8-bit mantissas, 1/32 octave (Elite)", logmethod(8, 5)),
        ("log/antilog, 10-bit mantissas, 1/1024 octave", logmethod(10, 10)),
    ]
    depth = (m.ZNEAR, 742000)
    for name, p in methods:
        worst = {}
        for band in (0.656, 4):
            w = 0
            for _ in range(n):
                z = int(depth[0] * (depth[1] / depth[0]) ** rnd.random())
                a = int(band * z)
                x = rnd.randint(-a, a)
                v = p(x, z)
                if v is None or abs(v) > 30000:
                    continue
                w = max(w, abs(v - float(m.FX * x / z)))
            worst[band] = w
        back_x = back_z = 0
        for _ in range(200):
            z = int(depth[0] * (depth[1] / depth[0]) ** rnd.random())
            prev = None
            for x in range(0, 4 * z, max(1, z // 2000)):
                v = p(x, z)
                back_x += prev is not None and v < prev
                prev = v
            x = rnd.randint(1, 1 << 21)
            prev, z = None, m.ZNEAR
            while z < depth[1]:
                v = p(x, z)
                back_z += prev is not None and v > prev
                prev, z = v, z + max(1, z // 2000)
        print(f"{name:52} on screen {worst[0.656]:6.2f}, |X| <= 4Z {worst[4]:6.2f}, "
              f"backwards in X {back_x}, in Z {back_z}")


def main():
    out = sys.argv[1]
    if out == "--survey":
        survey()
        return
    if len(sys.argv) > 2 and sys.argv[2] == "--cases":
        import json
        with open(sys.argv[3], "w") as f:
            json.dump(cases(), f)
        return
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "consts.6502"), "w") as f:
        f.write(consts())
    with open(os.path.join(out, "tables.6502"), "w") as f:
        f.write(TABLES)


if __name__ == "__main__":
    main()
