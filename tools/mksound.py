#!/usr/bin/env python3
"""Driller's sounds for the SN76489, from the original's beeper, at build
time (docs/research/sound.md, src/sound.6502).

    mksound.py ZXSNAP OUTDIR [--edges FILE]
    mksound.py --check LOG.json SOUND.json

The first plays each of the original's 21 sounds ($9574 with A the
sound's number) on the ZX snapshot made from the fetched tape, on
SkoolKit's simulator with the 48K's contention (tools/zx.py), and logs the
beeper's level (port &FE's bit 4) as it changes, to the T-state. Each
sound is then cut into ticks, a field each (69,888 T-states: the ZX's
frame, and the BBC's field, 312 lines of 64us both), and each tick is
measured (analyse) and fitted with straight-line segments (fit) into a
script for the driver (tools/model/sound.py has the format), which plays
it back exactly as fitted (checked here, on the model). It writes
into OUTDIR:

    sound.6502   the scripts and their index, for src/sound.6502 (section
                 SoundData)
    sound.json   each sound's ticks as measured, its segments and bytes,
                 for the check and the research note

The second is tools/soundcheck.mjs's: the writes the disc made to the
chip, tick by tick, against the driver's model given the same requests.

Derived from the originals, so built, never committed (decision 6).

How a tick is measured: the beeper's level sampled every 28 T-states (the
SN76489's period unit: its tone counter steps at 4MHz / 16 / 2 = 125kHz,
and 3.5MHz / 125kHz = 28), so a period in samples is the chip's period
register. The waveform's own period is found by YIN's difference function
over the tick (de Cheveigne and Kawahara 2002: the first lag whose
cumulative-mean-normalised difference dips under YIN_THRESHOLD, else the
deepest), which is the cycle the beeper repeats however its code shapes a
cycle (the ROM-style beeper's cycles come with a short pulse between
calls; a sweep's cycles each a different length). Then of that period's
partials (its harmonics, up to PARTIALS and no higher than MAX_FREQ) the
strongest is the tone: the fundamental for a square or a pulse train, a
higher one where the beeper's cycle is a fast chirp (sounds 5 and 10).
Its strength against a square wave's fundamental is the attenuation, in
the chip's 2dB steps. A period past the tone channel's 10 bits (under
about 122Hz) is played as periodic noise, a fifteenth of tone 2's
frequency. A tick of a tone where YIN finds no period (its minimum over
NOISE_APERIODIC: a sweep running past what the beeper can sound, or the
sound ending early in the tick) holds the last period found. A sound whose
ticks are mostly aperiodic (that minimum over NOISE_APERIODIC at the
median: sound 13 alone) is white noise, clocked so its output changes as
often as the beeper's did, as loud as the beeper's waveform was.
"""
import json
import math
import os
import statistics
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from tools.model import sound as drv  # noqa: E402

HEADER = "\\ Generated by tools/mksound.py from Driller's snapshot: don't edit."

FIELD = 69888           # T-states a tick: the ZX's frame, the BBC's field
UNIT = 28               # T-states a sample: the SN76489's period unit
W = FIELD // UNIT       # samples a tick
LAGS = 2 * W            # the longest period looked for: two ticks
YIN_THRESHOLD = 0.15
NOISE_APERIODIC = 0.5
PARTIALS = 64
MIN_PERIOD = 8          # the highest partial taken: 125kHz / 8, 15.6kHz
TONE_MAX = 1023         # the tone register's 10 bits
PERIODIC_DIVISOR = 15   # the periodic noise's period in tone 2's cycles
SOUND = 0x9574          # the original's: play sound A
BEEPER = 0x10           # port &FE's bit 4

# How closely a segment follows the ticks: the period within a 64th (a
# quarter of a semitone) or 1, the attenuation within a step.
PERIOD_TOLERANCE = 64
ATT_TOLERANCE = 1


def record(snap):
    """Each sound's port &FE writes, (T-state from the call, value), and
    its length in T-states: the original run from the snapshot."""
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    from zx import Spectrum
    from skoolkit.simutils import A, T
    out = {}
    for n in range(1, drv.SOUNDS + 1):
        log = []
        s = Spectrum(snap, portlog=log, contended=True)
        s.regs[A] = n
        t0 = s.regs[T]
        (length,) = s.call(SOUND)
        out[n] = {"length": length, "outs": [(t - t0, v) for (t, _, v) in log]}
    return out


def wave(rec):
    """The beeper's level a sample at a time, silent after the sound."""
    import numpy as np
    n = rec["length"] // UNIT + 1
    x = np.zeros(n + W + LAGS + 1)
    level, last = 0, 0
    for t, v in rec["outs"]:
        i = t // UNIT
        x[last:i] = level
        level, last = 1 if v & BEEPER else 0, i
    x[last:n] = level
    return x


def yin(seg):
    """The period of seg's first W samples (by lags up to LAGS) and its
    aperiodicity, YIN's normalised difference there."""
    import numpy as np
    w = seg[:W]
    size = 1 << math.ceil(math.log2(len(seg) + W))
    cross = np.fft.irfft(np.fft.rfft(seg, size) * np.conj(np.fft.rfft(w, size)), size)[:LAGS + 1]
    sq = np.concatenate([[0.0], np.cumsum(seg * seg)])
    energy = sq[W:W + LAGS + 1] - sq[:LAGS + 1]
    diff = np.sum(w * w) + energy - 2 * cross
    diff[0] = 0
    mean = np.cumsum(diff[1:]) / np.arange(1, LAGS + 1)
    norm = np.ones(LAGS + 1)
    norm[1:] = diff[1:] / np.where(mean > 0, mean, 1)
    for t in range(2, LAGS):
        if norm[t] < YIN_THRESHOLD:
            while t < LAGS and norm[t + 1] < norm[t]:
                t += 1
            return t, float(norm[t])
    t = int(np.argmin(norm[2:])) + 2
    return t, float(norm[t])


def strongest(seg, tau):
    """Of period tau's partials, the strongest: (its period, its amplitude
    against a square wave's fundamental)."""
    import numpy as np
    span = seg[:(W // tau) * tau] if tau <= W else seg[:tau]
    t = np.arange(len(span))
    best = (0.0, tau)
    for k in range(1, PARTIALS + 1):
        if tau / k < MIN_PERIOD:
            break
        a = 2 * abs(np.sum(span * np.exp(-2j * np.pi * k * t / tau))) / len(span)
        if a > best[0] + 1e-9:
            best = (a, tau / k)
    return best[1], best[0] / (2 / math.pi)


def attenuation(r):
    """An amplitude ratio as the chip's attenuation, 2dB a step."""
    if r <= 0:
        return 15
    return max(0, min(15, round(-10 * math.log10(r))))


def analyse(rec):
    """A sound's ticks: (mode, period, attenuation) each, and what was
    measured."""
    import numpy as np
    if not rec["outs"]:
        return [], []
    x = wave(rec)
    ticks = max(1, round(rec["length"] / FIELD))
    meas = []
    for j in range(ticks):
        seg = x[j * W:j * W + W + LAGS + 1]
        w = seg[:W]
        if w.min() == w.max():
            meas.append(None)
            continue
        tau, q = yin(seg)
        meas.append({"tau": tau, "aperiodic": round(q, 3), "changes": int(np.sum(np.abs(np.diff(w)))),
                     "rms": round(2 * float(np.std(w)), 3)})
    sounding = [m for m in meas if m]
    noisy = statistics.median(m["aperiodic"] for m in sounding) > NOISE_APERIODIC
    # A tick of a tone with no period to be found (where a sweep runs past
    # what the beeper can sound, or the sound ends early in it) holds the
    # period of the last tick that had one (or the next, at the start).
    periodic = [j for j, m in enumerate(meas) if m and m["aperiodic"] <= NOISE_APERIODIC]
    for j, m in enumerate(meas):
        if m is None:
            continue
        held = m["tau"]
        if periodic and m["aperiodic"] > NOISE_APERIODIC:
            before = [k for k in periodic if k < j]
            held = meas[before[-1] if before else periodic[0]]["tau"]
        period, r = strongest(x[j * W:j * W + W + LAGS + 1], held)
        m.update({"held": held != m["tau"], "period": round(period, 2), "amplitude": round(r, 3)})
    out = []
    for m in meas:
        if m is None:
            out.append((drv.SILENT, 0, 15))
        elif noisy:
            # the noise's output changes at half its clock's rate, on average
            out.append((drv.WHITE, max(1, min(TONE_MAX, round(W / (2 * m["changes"])))), attenuation(m["rms"])))
        elif m["period"] <= TONE_MAX + 0.5:
            out.append((drv.TONE, max(1, round(m["period"])), attenuation(m["amplitude"])))
        else:
            out.append((drv.PERIODIC, min(TONE_MAX, round(m["period"] / PERIODIC_DIVISOR)), attenuation(m["amplitude"])))
    return out, meas


def close(got, want):
    (gm, gp, ga), (wm, wp, wa) = got, want
    if gm != wm:
        return False
    if wm == drv.SILENT:
        return True
    return abs(gp - wp) <= max(1, wp // PERIOD_TOLERANCE) and abs(ga - wa) <= ATT_TOLERANCE and 1 <= gp <= TONE_MAX \
        and 0 <= ga <= 15


def run_of(ticks, j, per, att, n):
    """The ticks a segment from tick j plays, n of them, starting from per
    and att (12.4 and 4.4) and aiming at tick j + n - 1's: (dper, datt,
    the outputs), or None if a slope won't fit its field."""
    mode, p1, a1 = ticks[j + n - 1]
    dper = round((16 * p1 + 8 - per) / (n - 1)) if n > 1 else 0
    datt = round((16 * a1 + 8 - att) / (n - 1)) if n > 1 else 0
    if not (-32768 <= dper < 32768 and -128 <= datt < 128):
        return None
    outs = []
    for k in range(n):
        p, a = per + k * dper, att + k * datt
        if not (0 <= p < 65536 and 0 <= a < 256):
            return None
        outs.append((mode, p >> 4, a >> 4))
    return dper, datt, outs


def fit(ticks):
    """Segments for a sound's ticks: (count, mode, per, dper, att, datt),
    each as long as it can be while every tick it plays is close to the
    measured one, from the tick's own values or, where that goes further,
    from where the last segment left the period or the attenuation."""
    segs = []
    j = 0
    run = None
    while j < len(ticks):
        mode = ticks[j][0]
        if mode == drv.SILENT:
            n = 1
            while j + n < len(ticks) and ticks[j + n][0] == drv.SILENT and n < 255:
                n += 1
            segs.append((n, mode, 0, 0, 16 * 15, 0))
            j += n
            continue
        fresh = (16 * ticks[j][1] + 8, 16 * ticks[j][2] + 8)
        starts = [fresh]
        if run and run[0] == mode:
            starts += [(run[1], fresh[1]), (fresh[0], run[2]), (run[1], run[2])]
        best = None
        for per, att in starts:
            n, good = 0, None
            while j + n < len(ticks) and n < 255 and ticks[j + n][0] == mode:
                r = run_of(ticks, j, per, att, n + 1)
                if r is None or not all(close(o, t) for o, t in zip(r[2], ticks[j:j + n + 1])):
                    break
                n += 1
                good = r
            if n and (best is None or n > best[0]):
                best = (n, per, att, good)
        assert best, f"tick {j} fits no segment"
        n, per, att, (dper, datt, _) = best
        segs.append((n, mode, per, dper, att, datt))
        run = (mode, (per + n * dper) & 0xFFFF, (att + n * datt) & 0xFF)
        j += n
    return segs


def encode(segs):
    out = []
    for seg in segs:
        out += drv.segment_bytes(*seg)
    return out + [0]


def build(snap, outdir, edges=None):
    if edges and os.path.exists(edges):
        recs = {int(k): v for k, v in json.load(open(edges)).items()}
    else:
        recs = record(snap)
        if edges:
            json.dump(recs, open(edges, "w"))
    blob, index, sounds = [], {}, {}
    for n in range(1, drv.SOUNDS + 1):
        ticks, meas = analyse(recs[n])
        segs = fit(ticks)
        script = encode(segs)
        # sounds alike share their script (5 and 10 are one routine)
        for m, s in sounds.items():
            if s["bytes"] == script:
                index[n] = index[m]
                break
        else:
            index[n] = len(blob)
            blob += script
        sounds[n] = {"length": recs[n]["length"], "ticks": ticks, "measured": meas, "segments": segs, "bytes": script}
    # The scripts must play what was fitted: each sound alone on the model.
    for n, s in sounds.items():
        d = drv.Driver(blob, index)
        d.ask(n)
        for t, want in enumerate(s["ticks"]):
            d.played = None
            d.tick()
            assert want[0] == drv.SILENT or (d.played and close(d.played, want)), \
                f"sound {n} tick {t}: {d.played} for {want}"
        d.tick()
        assert not d.busy(), f"sound {n} plays past its ticks"
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "sound.json"), "w") as f:
        json.dump({"blob": blob, "index": {str(k): v for k, v in index.items()},
                   "sounds": {str(k): v for k, v in sounds.items()}}, f)
    with open(os.path.join(outdir, "sound.6502"), "w") as f:
        f.write(HEADER + "\n")
        f.write(f"SND_SOUNDS = {drv.SOUNDS}\nSND_BYTES = {len(blob)}\n\n")
        f.write("SECTION SoundData\n")
        f.write("\\ each sound's script, 1 to SND_SOUNDS: low bytes, then high\n.snd_index_lo\n")
        f.write("    EQUB " + ", ".join(f"LO(snd_scripts + {index[n]})" for n in range(1, drv.SOUNDS + 1)) + "\n")
        f.write(".snd_index_hi\n")
        f.write("    EQUB " + ", ".join(f"HI(snd_scripts + {index[n]})" for n in range(1, drv.SOUNDS + 1)) + "\n")
        f.write(".snd_scripts\n")
        for i in range(0, len(blob), 16):
            f.write("    EQUB " + ", ".join(f"&{b:02X}" for b in blob[i:i + 16]) + "\n")
        f.write("ENDSECTION\n")
    for n, s in sounds.items():
        sounding = [t for t in s["ticks"] if t[0] != drv.SILENT]
        print(f"sound {n:2d}: {len(s['ticks']):3d} ticks, {len(s['segments']):3d} segments, "
              f"{len(s['bytes']):3d} bytes" + ("" if sounding else ", silent"))
    print(f"sound: {len(blob)} bytes of scripts, {2 * drv.SOUNDS} of index")


def check(log_path, sound_path):
    """The disc's writes against the model's: LOG has the requests, each
    (tick, sound), and the writes of every tick from the first; exit 1 on
    the first difference."""
    log = json.load(open(log_path))
    snd = json.load(open(sound_path))
    blob = snd["blob"]
    index = {int(k): v for k, v in snd["index"].items()}
    ticks = log["ticks"]
    want = drv.play(blob, index, [tuple(a) for a in log["asks"]], len(ticks))
    bad = 0
    if log["init"] != drv.INIT_WRITES:
        bad += 1
        print(f"sound: FAIL sound_init wrote {[hex(v) for v in log['init']]}, not {[hex(v) for v in drv.INIT_WRITES]}")
    for t, (w, g) in enumerate(zip(want, ticks)):
        if w != g:
            bad += 1
            if bad <= 10:
                print(f"sound: FAIL tick {t}: wrote {[hex(v) for v in g]}, the model {[hex(v) for v in w]}")
    writes = sum(len(w) for w in ticks)
    print(f"sound: {len(ticks)} ticks, {len(log['asks'])} sounds asked for, {writes} writes to the chip, "
          f"{len(ticks) - bad} ticks as the model's")
    return 1 if bad else 0


if __name__ == "__main__":
    a = sys.argv[1:]
    if a and a[0] == "--check":
        sys.exit(check(a[1], a[2]))
    edges = None
    if "--edges" in a:
        i = a.index("--edges")
        edges = a[i + 1]
        del a[i:i + 2]
    build(a[0], a[1], edges)
