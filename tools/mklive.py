#!/usr/bin/env python3
"""The live disc's data (src/live.6502), and the model's views of the
cameras its check saw (tools/livecheck.mjs).

    mklive.py DB.json AREAS.json OUTDIR
    mklive.py DB.json --render < cameras.json > views.json

The first form writes into OUTDIR:

    data.6502   for the assembly, included by src/live.6502:
                - the banks tools/mkareas.py's records fill (LIVE_RECORD_BANKS)
                  and where the last one's records end (LIVE_DATA_BANK,
                  LIVE_DATA_ORG), from AREAS.json;
                - section LiveData, after those records in that bank: each
                  area's name (TEXT_COLS characters, centred) and its
                  patterns (sky, then colour indices 1-15, four bytes each:
                  tools/model/colours.py's, decision 8b) in the records'
                  directory order; every entrance's area (its index in that
                  directory), Driller's id and camera (tools/model/camera.py's
                  from_entrance), in the database's order; and the step along
                  the view for each yaw;
    live.json   the same entrances, for the check.

The step is the model's walk (tools/objectcases.py's): LIVE_STEP world units
along the yaw, floor(LIVE_STEP sin / 64) across and floor(LIVE_STEP cos /
64) along z, from the original's sine table.

The second form reads a list of {"area": its directory index, "camera": [x,
y, z, yaw, pitch, roll]} and writes, for each, the model's view
(tools/model/render.py) as VIEW_H rows of VIEW_BYTES bytes in hex.

Derived from the originals (make data, make colours), so built, never
committed (decision 6).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tools.model import camera as cam, parts, render, view, writer  # noqa: E402

TEXT_COLS = view.read_defs()["SCREEN_COLS"] // 4
BANK_ORG, BANK_END = 0x8000, 0xC000
LIVE_STEP = 32                      # world units a frame's step: half a cell


def centred(text):
    text = text.strip()
    if len(text) > TEXT_COLS:
        raise SystemExit(f"{text!r} is wider than {TEXT_COLS} characters")
    return text.center(TEXT_COLS)


def equb(name, values, per=16):
    out = [f".{name}"]
    values = list(values)
    for i in range(0, len(values), per):
        out.append("    EQUB " + ", ".join(str(v) for v in values[i:i + per]))
    return out


def entrances(db, layout):
    index = {a["id"]: i for i, a in enumerate(layout["areas"])}
    out = []
    for area, e, c in cam.entrance_views(db):
        out.append({
            "name": render.name(area, e), "area": index[area["id"]], "area_id": area["id"],
            "area_name": area["name"].strip(), "entrance": e["id"],
            "camera": [c.x, c.y, c.z, c.yaw, c.pitch, c.roll],
        })
    return out


def generate(db, layout, out):
    by_id = {a["id"]: a for a in db["areas"]}
    areas = [by_id[a["id"]] for a in layout["areas"]]
    ens = entrances(db, layout)
    banks = sorted(int(b) for b in layout["banks"])
    last = max(banks)
    end = max(a["address"] + a["bytes"] for a in layout["areas"] if a["bank"] == last)
    sin, cos = db["tables"]["sin"], db["tables"]["cos"]
    for v in ens:
        assert all(0 <= p < 0x8000 for p in v["camera"][:3]), v
        assert 0 <= v["entrance"] < 100, v          # (two digits on the screen)

    L = [
        "\\ Generated by tools/mklive.py from Driller's data (decision 6): never",
        "\\ committed; included by src/live.6502, which documents the layout.",
        f"LIVE_AREAS = {len(areas)}",
        f"LIVE_ENTRANCES = {len(ens)}",
        "LIVE_RECORD_BANKS = {" + ", ".join(str(b) for b in banks) + "}",
        f"LIVE_DATA_BANK = {last}",
        f"LIVE_DATA_ORG = &{end:04X}",
        f"LIVE_STEP = {LIVE_STEP}",
        f"LIVE_TEXT_COLS = {TEXT_COLS}",
        f"LIVE_DISPLAY = \"{parts.colours.DISPLAY}\"",
        "",
        f"SECTION LiveData, org = LIVE_DATA_ORG, guard = &{BANK_END:04X}, filename = \"LDATA\", cmos = TRUE",
    ]
    names = "".join(centred(a["name"]) for a in areas).encode("ascii")
    L += equb("ld_names", names)
    pats = []
    for a in areas:
        pats += list(parts.sky(a))
        for c in range(1, 16):
            pats += list(parts.pattern(a, c))
    L += equb("ld_pats", pats)
    for name, f in (("en_area", lambda v: v["area"]), ("en_id", lambda v: v["entrance"]),
                    ("en_xl", lambda v: v["camera"][0] & 255), ("en_xh", lambda v: v["camera"][0] >> 8),
                    ("en_yl", lambda v: v["camera"][1] & 255), ("en_yh", lambda v: v["camera"][1] >> 8),
                    ("en_zl", lambda v: v["camera"][2] & 255), ("en_zh", lambda v: v["camera"][2] >> 8),
                    ("en_yaw", lambda v: v["camera"][3]), ("en_pitch", lambda v: v["camera"][4]),
                    ("en_roll", lambda v: v["camera"][5])):
        L += equb(name, (f(v) for v in ens))
    # The step for each yaw, signed bytes.
    L += equb("st_dx", ((LIVE_STEP * sin[y]) // 64 & 255 for y in range(cam.STEPS)))
    L += equb("st_dz", ((LIVE_STEP * cos[y]) // 64 & 255 for y in range(cam.STEPS)))
    L.append("ENDSECTION")
    out.mkdir(parents=True, exist_ok=True)
    (out / "data.6502").write_text("\n".join(L) + "\n")
    (out / "live.json").write_text(json.dumps({
        "display": parts.colours.DISPLAY, "step": LIVE_STEP, "entrances": ens,
        "areas": [{"index": i, "id": a["id"], "name": a["name"].strip()} for i, a in enumerate(areas)],
    }, indent=1) + "\n")
    print(f"live: {len(ens)} entrances in {len(areas)} areas; records in banks {banks}, "
          f"bank {last}'s from &{end:04X} free")


def render_cameras(db, layout_areas, cameras):
    by_id = {a["id"]: a for a in db["areas"]}
    out = []
    for c in cameras:
        area = by_id[layout_areas[c["area"]]["id"]]
        v = render.render(db, area, cam.Camera(*c["camera"]))
        out.append([row.hex() for row in writer.view_bytes(v.lines)])
    return out


def main(argv):
    if len(argv) == 3 and argv[2] == "--render":
        db = json.loads(Path(argv[1]).read_text())
        req = json.load(sys.stdin)
        json.dump(render_cameras(db, req["areas"], req["cameras"]), sys.stdout)
        return 0
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    db = json.loads(Path(argv[1]).read_text())
    layout = json.loads(Path(argv[2]).read_text())
    generate(db, layout, Path(argv[3]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
