#!/usr/bin/env python3
"""The 6502 logic's data, from Driller's tape and the in-play snapshot.

    .venv/bin/python -I tools/mklogicdata.py build/zx/driller.z80 originals/zx/Driller.tzx build/logic6502

writes into that directory:

    db.bin        Driller's database, the ZX's bytes from the tape's block
                  as the original holds them at ($8912), with the port's
                  first step and turn (below): the logic walks it in its
                  sideways RAM bank (src/logic/bank.6502)
    data.6502     baron lists and constants: the variables' first values
                  (the in-play snapshot: area 1, entrance 19, on the probe,
                  with the port's start), the original's tables the logic
                  reads, and the live disc's pace; include it before
                  src/logic/vars.6502
    layout.json   where each of the original's variables is, for
                  tools/logiccheck.mjs

The original keeps most of the logic's variables in one block, $8762 on,
with its tables among them, and the FCL reaches far into it: variable n
is at $887F + n - 1 for any n, so SETVAR can write the bytes after the 32
variables (the flags, the tables). The 6502 keeps that block whole, at the
original's offsets ("the mirror", ZXV_ORG to ZXV_END), so those aliases
hold. The rest of the variables (tools/logic/state.py) each get their own
place. Six words in the mirror point into the database; the 6502's point
into its copy, so they're moved by the database's new address
(ZXV_PTRS).

The port starts with smaller steps and turns than the original (decision
48): tools/logic/state.py's port_start sets the database's first step and
turn, and the variables a new game sets from them, to START_STEP_INDEX and
START_TURN_INDEX, as the checks' traces start (tools/logictrace.py,
tools/mklive.py --trace). The pace, PASS_FIELDS and REPEAT_FIELDS, is set
beside them and goes into data.6502 for src/live.6502.

Nothing of Driller's is committed: this reads it from the fetched tape and
the snapshot made from it, into build/.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import freescape  # noqa: E402
from logic.oracle import Original  # noqa: E402
from logic import rig  # noqa: E402
from logic.passes import _action_of  # noqa: E402
from logic.state import VARS, DATABASE, PASS_FIELDS, REPEAT_FIELDS, State, database, port_start  # noqa: E402

HEADER = "\\ Generated by tools/mklogicdata.py from Driller's tape and snapshot: don't edit."

# The mirror: the original's variable block, $8762 up to the end of the
# FCL's reach. Variable n of the FCL is $887F + (n - 1 AND 255), up to
# $897E; an instruction's length is read at $8939 + op, up to $89B8.
ZXV_ORG = 0x8762
ZXV_END = 0x8939 + 0x80
# The words in the mirror that point into the database.
ZXV_PTR_ADDRS = {
    0x8864: "AreaObjPtr", 0x8866: "AreaNamePtr", 0x8868: "AreaCondPtr",
    0x8912: "the database", 0x8914: "the area table", 0x8922: "the global conditions",
}
# The original's tables the logic reads outside the mirror: constant in
# play, so they go in the bank with the code.
SINCOS = 0x8E78         # 72 (sin, cos) pairs, signed, 1.0 = 64
KEY_TABLE = 0x8FC8      # key, action, shooting action; then key, action
KEY_CODES = 0x9414      # a code for each key, 5 a half-row
OBJECT_TYPE_COUNTS = 0x8929


def blist(name, values):
    values = list(values)
    lines = [f"{name} = {{"]
    for i in range(0, len(values), 16):
        chunk = ", ".join(str(v) for v in values[i:i + 16])
        lines.append(f"    {chunk}{',' if i + 16 < len(values) else ''}")
    lines.append("}")
    return "\n".join(lines)


def word(m, a):
    return m[a] | m[a + 1] << 8


def size_of(size):
    return size if isinstance(size, int) else size[1]


def area_record(m, area_id):
    base, table = word(m, 0x8912), word(m, 0x8914)
    for i in range(m[DATABASE]):
        a = base + word(m, table + 2 * i)
        if m[a + 2] == area_id:
            return a
    raise KeyError(area_id)


def areas(m):
    """(id, object count) of each area, as the area table lists them."""
    base, table = word(m, 0x8912), word(m, 0x8914)
    out = []
    for i in range(m[DATABASE]):
        a = base + word(m, table + 2 * i)
        out.append((m[a + 2], m[a + 1]))
    return out


def main():
    snap, tape, out = sys.argv[1:4]
    m = Original(snap).memory()
    block = freescape.data_block(open(tape, "rb").read())
    lo, hi = database(m)
    db = block[lo - freescape.LOAD:hi - freescape.LOAD]
    # The snapshot is the original in play at the start, before anything
    # has changed the database: the same bytes as the tape's.
    assert bytes(m[lo:hi]) == db, "the snapshot's database isn't the tape's"
    assert lo == DATABASE and word(m, 0x8912) == DATABASE
    # The port's start (decision 48), in the database and the variables.
    m = port_start(m)
    db = m[lo:hi]
    for a in ZXV_PTR_ADDRS:
        assert lo <= word(m, a) < hi, f"${a:04X} doesn't point into the database"
    mirror = m[ZXV_ORG:ZXV_END]
    n3, n2 = m[0x8FC6], m[0x8FC7]
    outside = [(n, a, size_of(sz)) for n, a, sz, _, _ in VARS if not ZXV_ORG <= a < ZXV_END]
    for n, a, sz, _, _ in VARS:
        if ZXV_ORG <= a < ZXV_END:
            assert a + size_of(sz) <= ZXV_END, n
    # Each key code's action, and its action in shooting mode, as the
    # original's search of its key table finds them ($99EF), for every code
    # the keyboard gives (its table at KEY_CODES, all below &80).
    codes = m[KEY_CODES:KEY_CODES + 40]
    assert max(codes) < 0x80
    s = State(m)
    actions = []
    for shoot in (0, 0xFF):
        s.ShootMode = shoot
        actions.append([_action_of(s, c) for c in range(0x80)])
    # The 6502 keeps them densely (src/logic/pass.6502's action_of): the
    # keys' codes run from KEY_LOW to KEY_LOW + KEY_SPAN - 1 in a table,
    # SPACE is the one action below them and none are above, and in
    # shooting mode the four movement actions 3 to 6 become 29 less.
    key_low = 48
    key_span = 91 - key_low
    key_actions = actions[0][key_low:key_low + key_span]

    def dense(code, shoot):
        if code < key_low:
            return 30 if code == 32 else 0x7F
        if code >= key_low + key_span:
            return 0x7F
        a = key_actions[code - key_low]
        return 29 - a if shoot and 3 <= a <= 6 else a

    for c in codes:
        for shoot in (0, 1):
            assert dense(c, shoot) == actions[shoot][c], f"key code {c}"
    most = max(n for _, n in areas(m))
    # src/logic/area.6502's place_rigs indexes the rigs by the area's id less
    # one for ids below &13, as the original's JP P on the id less &13 picks
    # them: true of every id from 1 to &7F.
    assert all(0 < a < 0x80 for a, _ in areas(m)), "an area id outside 1-127"
    # src/logic/rig.6502 multiplies a percentage by a yield unsigned, as the
    # original's signed $928C does for yields below &80; and divides by the
    # gas's reach, which it takes to be non-zero in every area with rigs.
    assert max(m[rig.GAS_TABLE:rig.GAS_TABLE + 15 + 18]) < 0x80, "a gas yield of &80 or more"
    for a, _ in areas(m):
        if a < 0x13:
            assert m[area_record(m, a) + 12], f"area {a}'s gas has no reach"
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "db.bin"), "wb") as f:
        f.write(db)
    lines = [
        HEADER,
        "",
        f"ZX_DB = &{lo:04X}                \\ the database's address in the original",
        f"DB_LEN = {hi - lo}",
        f"ZXV_ORG = &{ZXV_ORG:04X}",
        f"ZXV_END = &{ZXV_END:04X}",
        f"ZX_N_GLOBALS = {m[0x890F]}",
        f"ZX_AREAS_MOST = {most}          \\ the most objects in an area",
        f"ZX_KEYS3 = {n3}",
        f"ZX_KEYS2 = {n2}",
        "",
        "\\ the live disc's pace (decision 48: tools/logic/state.py's, with the port's start)",
        f"PASS_FIELDS = {PASS_FIELDS}",
        f"REPEAT_FIELDS = {REPEAT_FIELDS}",
        "",
        "\\ the mirror's first bytes, and the offsets in it of the words that point",
        "\\ into the database",
        blist("ZXV_INIT", mirror),
        blist("ZXV_PTRS", [a - ZXV_ORG for a in sorted(ZXV_PTR_ADDRS)]),
        "",
        "\\ the variables outside the mirror, their first bytes",
        *(blist(f"ZXI_{n}", m[a:a + sz]) for n, a, sz in outside),
        "",
        "\\ the original's tables",
        blist("ZX_SINCOS", m[SINCOS:SINCOS + 144]),
        blist("ZX_KEY_TABLE", m[KEY_TABLE:KEY_TABLE + 3 * n3 + 2 * n2]),
        blist("ZX_KEY_CODES", m[KEY_CODES:KEY_CODES + 40]),
        "\\ the rigs' messages, 14 characters each, but the two its figures go",
        "\\ into (RigFigures, a variable): those before them, and those after",
        f"ZX_RIG_MESSAGES = &{rig.AREA_NEUTRAL:04X}",
        f"ZX_RIG_FIGURES = &{rig.CFT:04X}",
        f"ZX_RIG_MESSAGES_B = &{rig.ENERGY_TOO_LOW:04X}",
        blist("ZX_RIG_MSG_A", m[rig.AREA_NEUTRAL:rig.CFT]),
        blist("ZX_RIG_MSG_B", m[rig.ENERGY_TOO_LOW:rig.NO_RIG_PLACED + rig.MESSAGE_LEN]),
        "",
        "\\ the action of each key code from KEY_LOW up, from the key table as $99EF",
        "\\ finds it (the other codes and shooting mode: action_of)",
        f"KEY_LOW = {key_low}",
        blist("ZX_ACTIONS", key_actions),
        "",
    ]
    with open(os.path.join(out, "data.6502"), "w") as f:
        f.write("\n".join(lines))
    layout = {
        "mirror": [ZXV_ORG, ZXV_END],
        "pointers": sorted(ZXV_PTR_ADDRS),
        "database": [lo, hi],
        "vars": [{"name": n, "addr": a, "size": size_of(sz), "kind": k} for n, a, sz, k, _ in VARS],
    }
    with open(os.path.join(out, "layout.json"), "w") as f:
        json.dump(layout, f, indent=1)
    print(f"logic data: database {hi - lo} bytes, mirror ${ZXV_ORG:04X}-${ZXV_END - 1:04X}, "
          f"{len(outside)} variables outside it, {len(areas(m))} areas of up to {most} objects")


if __name__ == "__main__":
    main()
